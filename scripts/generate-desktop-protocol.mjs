import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(repositoryRoot, "protocol/desktop-protocol.v1.json");
const outputPath = path.join(repositoryRoot, "src/protocol/generated-desktop-protocol.ts");

export async function generateDesktopProtocol() {
  const schema = JSON.parse(await readFile(schemaPath, "utf8"));
  if (schema.version !== 1 || !Array.isArray(schema.commands)) {
    throw new Error("Desktop protocol schema must declare version 1 and a command list.");
  }
  const names = new Set();
  for (const command of schema.commands) {
    if (!command.name || names.has(command.name)) {
      throw new Error(`Desktop protocol contains an invalid or duplicate command: ${command.name}`);
    }
    names.add(command.name);
  }

  const lines = [
    "// Generated by scripts/generate-desktop-protocol.mjs. Do not edit by hand.",
    'import type * as Model from "../models";',
    'import type { WindowChromeMode } from "../workbench/window-chrome";',
    "",
    `export const DESKTOP_PROTOCOL_VERSION = ${schema.version} as const;`,
    "",
    "export interface DesktopCommandMap {",
  ];
  for (const command of schema.commands) {
    const entries = Object.entries(command.args);
    const args = entries.length === 0
      ? "Record<string, never>"
      : `{ ${entries.map(([name, type]) => `${name}: ${typescriptType(type)};`).join(" ")} }`;
    lines.push(`  ${command.name}: { args: ${args}; result: ${typescriptType(command.result)} };`);
  }
  lines.push(
    "}",
    "",
    "export type DesktopCommandName = keyof DesktopCommandMap;",
    "",
    "export const DESKTOP_RESULT_VALIDATORS: {",
    "  readonly [Command in DesktopCommandName]: string;",
    "} = {",
  );
  for (const command of schema.commands) {
    lines.push(`  ${command.name}: ${JSON.stringify(command.validator)},`);
  }
  lines.push("};", "");
  return `${lines.join("\n")}\n`;
}

function typescriptType(type) {
  if (type.startsWith("array:")) return `Array<${typescriptType(type.slice(6))}>`;
  if (type.startsWith("nullable:")) return `${typescriptType(type.slice(9))} | null`;
  if (["string", "number", "boolean", "void"].includes(type)) return type;
  if (type === "WindowChromeMode") return type;
  return `Model.${type}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(outputPath, await generateDesktopProtocol(), "utf8");
}
